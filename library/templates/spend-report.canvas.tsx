import {
  BarChart,
  Callout,
  Card,
  CardBody,
  CardHeader,
  Divider,
  Grid,
  H1,
  H2,
  Row,
  Stack,
  Stat,
  Table,
  Text,
} from 'cursor/canvas'

interface Metrics {
  events: number
  input_tokens: number
  output_tokens: number
  cache_write_tokens: number
  cache_read_tokens: number
  total_tokens: number
  cost_cents: number
  cursor_fee_cents?: number
  included_cost_cents?: number
  included_fee_cents?: number
}

interface SliceRow {
  key: string
  metrics: Metrics
}

interface Coverage {
  known_events: number
  total_events: number
  known_token_percent: number | null
}

interface SpendReport {
  scope?: string
  period: { days: number; start: string; end: string; source: string }
  attribution_sources: {
    instances?: number
    workspaces_scanned: number
    embedded_installations_scanned: number
  }
  instances?: Array<{
    label: string
    synced_at: string
    harness_version: string
    records_in_window: number
    records_selected: number
    totals: Metrics
  }>
  totals: Metrics
  daily: Array<Metrics & { date: string }>
  slices: Record<string, SliceRow[]>
  coverage: Record<string, Coverage>
  warnings: string[]
}

// Generated by `pan spend --canvas` from the aggregate report JSON. The
// untyped constant lets the report carry fields this layout does not read.
const REPORT_DATA = __SPEND_REPORT__
const REPORT: SpendReport = REPORT_DATA

const MONTHS = [
  'Jan',
  'Feb',
  'Mar',
  'Apr',
  'May',
  'Jun',
  'Jul',
  'Aug',
  'Sep',
  'Oct',
  'Nov',
  'Dec',
]
const COVERAGE_LABELS: Record<string, string> = {
  command: 'command',
  persona: 'persona and model',
  tools: 'tools',
  fast_mode: 'Fast mode',
  governance: 'governance',
  workflow_role: 'workflow role',
  stage: 'stage',
  remediation: 'remediation',
}

const fee = (m: Metrics) => m.cursor_fee_cents ?? 0
const included = (m: Metrics) => m.included_cost_cents ?? 0
const onDemand = (m: Metrics) => m.cost_cents - included(m)
const onDemandFee = (m: Metrics) => fee(m) - (m.included_fee_cents ?? 0)
const usd = (cents: number) =>
  `$${(cents / 100).toLocaleString('en-US', { maximumFractionDigits: 0 })}`
const usd2 = (cents: number) =>
  `$${(cents / 100).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
const pct = (part: number, whole: number) =>
  whole > 0 ? `${((part / whole) * 100).toFixed(1)}%` : '0.0%'
const n = (v: number) => v.toLocaleString('en-US')
const mtok = (tokens: number) => Math.round(tokens / 1e6)
const dollars = (cents: number) => Math.round(cents / 100)
const isUnattributed = (key: string) => key.toLowerCase() === 'unattributed'
const isOther = (key: string) => key === 'Other'
const day = (iso: string) =>
  `${MONTHS[Number(iso.slice(5, 7)) - 1]} ${Number(iso.slice(8, 10))}`
const stamp = (iso: string) => `${iso.slice(0, 10)} ${iso.slice(11, 16)} UTC`

function byCost(rows: SliceRow[] | undefined): SliceRow[] {
  return [...(rows ?? [])]
    .filter((row) => row.metrics.events > 0)
    .sort(
      (a, b) =>
        Number(isOther(a.key)) - Number(isOther(b.key)) ||
        b.metrics.cost_cents - a.metrics.cost_cents,
    )
}

const totals = REPORT.totals
const total = totals.cost_cents
const totalFee = fee(totals)
const hasFee = totalFee > 0
const totalIncluded = included(totals)
const hasIncluded = totalIncluded > 0
const stackedCost = hasFee || hasIncluded
const includedSentence = hasIncluded
  ? ` Included usage covered ${usd(totalIncluded)} (${pct(totalIncluded, total)}) of charged cost, leaving ${usd(onDemand(totals))} on demand.`
  : ''
const cacheRead = totals.cache_read_tokens
const endHour = Number(REPORT.period.end.slice(11, 13))
const lastDay = REPORT.daily.at(-1)
const partialLastDay =
  lastDay !== undefined &&
  lastDay.date === REPORT.period.end.slice(0, 10) &&
  endHour > 0
const dayLabel = (date: string) =>
  partialLastDay && date === lastDay?.date ? `${day(date)}*` : day(date)
const busiestDay = [...REPORT.daily].sort(
  (a, b) => b.cost_cents - a.cost_cents,
)[0]

const commands = byCost(REPORT.slices.commands)
const personaModels = byCost(REPORT.slices.persona_models)
const tools = byCost(REPORT.slices.tools).filter((row) => !isOther(row.key))
const stagesAll = byCost(REPORT.slices.stages)
const stages = stagesAll.filter(
  (row) => !isUnattributed(row.key) && !isOther(row.key),
)
const stageUnattributed = stagesAll.find((row) => isUnattributed(row.key))
const roles = byCost(REPORT.slices.workflow_role).map((row) =>
  row.key === 'stage' ? { ...row, key: 'stage worker' } : row,
)
const supervisor = roles.find((row) => row.key === 'supervisor')
const stageWorker = roles.find((row) => row.key === 'stage worker')
const fast = byCost(REPORT.slices.fast_mode)
const governance = byCost(REPORT.slices.governance)
const remediation = byCost(REPORT.slices.remediation)
const coverage = Object.entries(REPORT.coverage)
  .map(([key, value]) => ({
    label: COVERAGE_LABELS[key] ?? key,
    ...value,
    percent: value.known_token_percent ?? 0,
  }))
  .sort((a, b) => b.percent - a.percent)
const lowestCoverage = coverage.at(-1)
const instances = REPORT.instances ?? []

const scopeCaption =
  REPORT.scope === 'multi-instance'
    ? `${n(instances.length)} instances, duplicate events counted once`
    : `${n(REPORT.attribution_sources.workspaces_scanned)} workspaces and ${n(REPORT.attribution_sources.embedded_installations_scanned)} embedded installations scanned`

function sliceTable(rows: SliceRow[], label: string) {
  const headers = [
    label,
    'Events',
    'Charged cost',
    ...(hasIncluded ? ['On-demand', 'Included'] : []),
    'Share',
    ...(hasFee ? ['Cursor fee', 'Fee share'] : []),
    '$ / event',
    'Tokens (M)',
  ]

  return (
    <Table
      headers={headers}
      rows={rows.map(({ key, metrics: m }) => [
        key,
        n(m.events),
        usd(m.cost_cents),
        ...(hasIncluded ? [usd(onDemand(m)), usd(included(m))] : []),
        pct(m.cost_cents, total),
        ...(hasFee ? [usd(fee(m)), pct(fee(m), m.cost_cents)] : []),
        usd2(m.cost_cents / m.events),
        n(mtok(m.total_tokens)),
      ])}
      columnAlign={headers.map((_, index) => (index === 0 ? 'left' : 'right'))}
    />
  )
}

// Stacked segments that sum to charged cost: included usage, then on-demand
// usage split into model cost and Cursor fee when the report carries fees.
function costSeries(items: Metrics[]) {
  const includedSeries = hasIncluded
    ? [
        {
          name: 'Included usage (USD)',
          data: items.map((m) => dollars(included(m))),
        },
      ]
    : []
  const onDemandSeries = hasFee
    ? [
        {
          name: hasIncluded ? 'On-demand model cost (USD)' : 'Model cost (USD)',
          data: items.map((m) => dollars(onDemand(m) - onDemandFee(m))),
        },
        {
          name: hasIncluded ? 'On-demand Cursor fee (USD)' : 'Cursor fee (USD)',
          data: items.map((m) => dollars(onDemandFee(m))),
        },
      ]
    : [
        {
          name: hasIncluded ? 'On-demand cost (USD)' : 'Charged cost (USD)',
          data: items.map((m) => dollars(onDemand(m))),
        },
      ]

  return [...includedSeries, ...onDemandSeries]
}

function costChart(rows: SliceRow[], horizontal: boolean, height: number) {
  return (
    <BarChart
      categories={rows.map((r) => r.key)}
      series={costSeries(rows.map((r) => r.metrics))}
      horizontal={horizontal}
      stacked={stackedCost}
      valuePrefix="$"
      height={height}
    />
  )
}

function summaryCard(
  title: string,
  rows: SliceRow[],
  detail: (m: Metrics) => string,
  note: string,
) {
  return (
    <Card key={title}>
      <CardHeader>{title}</CardHeader>
      <CardBody>
        <Stack gap={8}>
          {rows.map((row) => (
            <Row key={row.key} justify="space-between">
              <Text>{row.key}</Text>
              <Text tone="secondary">{detail(row.metrics)}</Text>
            </Row>
          ))}
          <Divider />
          <Text tone="tertiary" size="small">
            {note}
          </Text>
        </Stack>
      </CardBody>
    </Card>
  )
}

const perEvent = (m: Metrics) =>
  `${usd(m.cost_cents)} · ${usd2(m.cost_cents / m.events)}/event`
const share = (m: Metrics) =>
  `${usd(m.cost_cents)} · ${pct(m.cost_cents, total)}`
const cards = [
  fast.length > 0 &&
    summaryCard(
      'Fast mode',
      fast,
      perEvent,
      'Fast mode is known only from an exact fast=true or fast=false model declaration. Max mode is not Fast mode.',
    ),
  governance.length > 0 &&
    summaryCard(
      'Governance',
      governance,
      share,
      'Ad hoc sessions ran without a Pancreator governance card.',
    ),
  remediation.length > 0 &&
    summaryCard(
      'Remediation',
      remediation,
      perEvent,
      'Remedial events ran under a remediator persona.',
    ),
].filter(Boolean)

// style: allow style.default_export Cursor Canvas renders the default export of a canvas file.
export default function SpendReportCanvas() {
  return (
    <Stack gap={28} style={{ padding: 24, maxWidth: 1100 }}>
      <Stack gap={6}>
        <H1>Cursor spend · last {REPORT.period.days} days</H1>
        <Text tone="secondary" size="small">
          Source: {REPORT.period.source} · {stamp(REPORT.period.start)} →{' '}
          {stamp(REPORT.period.end)} · charged cost
          {hasFee ? ' is model cost plus the Cursor token fee' : ''}
          {hasIncluded
            ? ', split into included usage and on-demand cost'
            : ''}{' '}
          · {scopeCaption}
        </Text>
      </Stack>

      <Grid columns={4 + Number(hasFee) + Number(hasIncluded)} gap={16}>
        {hasIncluded ? (
          <>
            <Stat
              value={usd(onDemand(totals))}
              label="On-demand cost"
              tone="info"
            />
            <Stat
              value={usd(totalIncluded)}
              label={`Included usage (${pct(totalIncluded, total)} of ${usd(total)} charged)`}
            />
          </>
        ) : (
          <Stat value={usd(total)} label="Charged cost" tone="info" />
        )}
        {hasFee && (
          <Stat
            value={usd(totalFee)}
            label={`Cursor fee (${pct(totalFee, total)} of cost)`}
          />
        )}
        <Stat value={n(totals.events)} label="Usage events" />
        <Stat
          value={`${(totals.total_tokens / 1e9).toFixed(2)}B`}
          label="Tokens"
        />
        <Stat
          value={pct(cacheRead, totals.total_tokens)}
          label="Tokens that are cache reads"
        />
      </Grid>

      {hasFee ? (
        <Callout
          tone="info"
          title={`The Cursor fee is ${pct(totalFee, total)} of charged cost`}
        >
          The fee is {usd(totalFee)} of {usd(total)}, a flat $0.25 per million
          tokens on models Cursor does not own. Cache reads are{' '}
          {pct(cacheRead, totals.total_tokens)} of tokens, so long cached
          contexts carry most of it.
          {supervisor && stageWorker
            ? ` The supervisor pays ${usd(fee(supervisor.metrics))} in fees against ${usd(fee(stageWorker.metrics))} for stage workers.`
            : ''}
          {includedSentence}
        </Callout>
      ) : (
        busiestDay && (
          <Callout
            tone="info"
            title={`${day(busiestDay.date)} was the most expensive day`}
          >
            It cost {usd(busiestDay.cost_cents)},{' '}
            {pct(busiestDay.cost_cents, total)} of the period.
            {includedSentence}
          </Callout>
        )
      )}

      {REPORT.daily.length > 0 && (
        <Grid columns={2} gap={24}>
          <Stack gap={10}>
            <H2>Daily charged cost</H2>
            <BarChart
              categories={REPORT.daily.map((d) => dayLabel(d.date))}
              series={costSeries(REPORT.daily)}
              stacked={stackedCost}
              valuePrefix="$"
              height={240}
            />
            <Text tone="tertiary" size="small">
              X axis: UTC day. Y axis: USD{stackedCost ? ', stacked' : ''}.
              {busiestDay
                ? ` The busiest day, ${day(busiestDay.date)}, cost ${usd(busiestDay.cost_cents)}.`
                : ''}
              {partialLastDay
                ? ` * The last day covers only its first ${endHour} hours.`
                : ''}
            </Text>
          </Stack>
          <Stack gap={10}>
            <H2>Daily tokens by category</H2>
            <BarChart
              categories={REPORT.daily.map((d) => dayLabel(d.date))}
              series={[
                {
                  name: 'Input (M)',
                  data: REPORT.daily.map((d) => mtok(d.input_tokens)),
                },
                {
                  name: 'Output (M)',
                  data: REPORT.daily.map((d) => mtok(d.output_tokens)),
                },
                {
                  name: 'Cache write (M)',
                  data: REPORT.daily.map((d) => mtok(d.cache_write_tokens)),
                },
                {
                  name: 'Cache read (M)',
                  data: REPORT.daily.map((d) => mtok(d.cache_read_tokens)),
                },
              ]}
              stacked
              height={240}
            />
            <Text tone="tertiary" size="small">
              X axis: UTC day. Y axis: millions of tokens, stacked by category.
            </Text>
          </Stack>
        </Grid>
      )}

      {(stages.length > 0 || roles.length > 0) && (
        <Grid columns={2} gap={24}>
          {stages.length > 0 && (
            <Stack gap={10}>
              <H2>Cost by workflow stage</H2>
              {costChart(stages, true, 230)}
              <Text tone="tertiary" size="small">
                Y axis: stage. X axis: USD{stackedCost ? ', stacked' : ''}.
                {stageUnattributed
                  ? ` Unattributed events (${usd(stageUnattributed.metrics.cost_cents)}) are omitted.`
                  : ''}
              </Text>
            </Stack>
          )}
          {roles.length > 0 && (
            <Stack gap={10}>
              <H2>Cost by workflow role</H2>
              {costChart(roles, true, 230)}
              <Text tone="tertiary" size="small">
                Y axis: role. X axis: USD{stackedCost ? ', stacked' : ''}.
                Unattributed events came from sessions without Pancreator
                transcripts.
              </Text>
            </Stack>
          )}
        </Grid>
      )}

      {commands.length > 0 && (
        <Stack gap={10}>
          <H2>Cost by command</H2>
          {sliceTable(commands, 'Command')}
        </Stack>
      )}

      {personaModels.length > 0 && (
        <Stack gap={10}>
          <H2>Cost by persona and model</H2>
          {sliceTable(personaModels, 'Persona · model')}
          {hasFee && (
            <Text tone="tertiary" size="small">
              Fee share differs by model because the fee is charged per token
              and model prices differ.
            </Text>
          )}
        </Stack>
      )}

      {cards.length > 0 && (
        <Grid columns={cards.length} gap={20}>
          {cards}
        </Grid>
      )}

      {tools.length > 0 && (
        <Stack gap={10}>
          <H2>Cost of conversations that used each tool</H2>
          <BarChart
            categories={tools.map((t) => t.key)}
            series={[
              {
                name: 'Charged cost (USD)',
                data: tools.map((t) => dollars(t.metrics.cost_cents)),
              },
            ]}
            horizontal
            valuePrefix="$"
            height={280}
          />
          <Text tone="tertiary" size="small">
            Y axis: tool. X axis: charged cost in USD of conversations that
            called the tool. Cursor does not meter per tool, so a conversation
            counts under every tool it used and bars overlap.
          </Text>
        </Stack>
      )}

      <Grid columns={instances.length > 0 ? 2 : 1} gap={24}>
        {instances.length > 0 && (
          <Stack gap={10}>
            <H2>Instances</H2>
            <Table
              headers={[
                'Machine',
                'Harness',
                'Synced',
                'Selected events',
                'Cost',
                ...(hasIncluded ? ['Included'] : []),
                ...(hasFee ? ['Cursor fee'] : []),
              ]}
              rows={instances.map((i) => [
                i.label,
                i.harness_version,
                stamp(i.synced_at),
                `${n(i.records_selected)} of ${n(i.records_in_window)}`,
                usd(i.totals.cost_cents),
                ...(hasIncluded ? [usd(included(i.totals))] : []),
                ...(hasFee ? [usd(fee(i.totals))] : []),
              ])}
              columnAlign={[
                'left',
                'left',
                'left',
                'right',
                'right',
                ...(hasIncluded ? ['right' as const] : []),
                ...(hasFee ? ['right' as const] : []),
              ]}
            />
            <Text tone="tertiary" size="small">
              Each event is credited once, to the instance with the better
              attribution for it.
            </Text>
          </Stack>
        )}
        {coverage.length > 0 && (
          <Stack gap={10}>
            <H2>Attribution coverage</H2>
            <Table
              headers={['Dimension', 'Known events', 'Known token share']}
              rows={coverage.map((c) => [
                c.label,
                n(c.known_events),
                `${c.percent.toFixed(1)}%`,
              ])}
              columnAlign={['left', 'right', 'right']}
              rowTone={coverage.map((c) =>
                c.percent < 50 ? 'warning' : undefined,
              )}
            />
            {lowestCoverage && (
              <Text tone="tertiary" size="small">
                Lowest coverage: {lowestCoverage.label} at{' '}
                {lowestCoverage.percent.toFixed(1)}% of tokens.
              </Text>
            )}
          </Stack>
        )}
      </Grid>

      {REPORT.warnings.length > 0 && (
        <Stack gap={6}>
          <H2>Report notes</H2>
          {REPORT.warnings.map((warning) => (
            <Text key={warning} tone="secondary" size="small">
              {warning}
            </Text>
          ))}
        </Stack>
      )}
    </Stack>
  )
}
